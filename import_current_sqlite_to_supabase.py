"""
Transactional SQLite -> Supabase PostgreSQL migration.

Source: data/evangelism.db (read-only)
Recovery backup: data/backups/evangelism_pre_migration_20261018_233106.db
Destination: mcn_migration_fresh_20261018

The destination must not already exist.
The existing live application and migration-test schema are not modified.
"""

import getpass
import hashlib
import json
import os
import re
import sqlite3
import sys
from datetime import datetime, timezone
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "data" / "evangelism.db"
BACKUP = ROOT / "data" / "backups" / "evangelism_pre_migration_20261018_233106.db"
REPORT = ROOT / "data" / "backups" / "supabase_migration_result.json"

SCHEMA = "mcn_migration_fresh_20261018"
EXPECTED_TABLES = 51
EXPECTED_ROWS = 956

def ident(value):
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", value or ""):
        raise RuntimeError(f"Unsafe SQL identifier encountered: {value!r}")
    return '"' + value + '"'

def pg_type(declared, is_identity=False):
    t = (declared or "").upper()
    if is_identity:
        return "BIGINT GENERATED BY DEFAULT AS IDENTITY"
    if "INT" in t:
        return "BIGINT"
    if any(x in t for x in ("REAL", "FLOA", "DOUB")):
        return "DOUBLE PRECISION"
    if "BLOB" in t:
        return "BYTEA"
    if any(x in t for x in ("NUMERIC", "DECIMAL")):
        return "NUMERIC"
    return "TEXT"

def pg_default(value):
    if value is None:
        return None
    value = str(value).strip()
    if len(value) >= 2 and value[0] == value[-1] == '"':
        inner = value[1:-1].replace("'", "''")
        return "'" + inner + "'"
    return value

def open_sqlite(path):
    if not path.is_file():
        raise RuntimeError(f"Database file is missing: {path}")
    con = sqlite3.connect(f"file:{path.resolve()}?mode=ro", uri=True)
    con.row_factory = sqlite3.Row
    con.execute("PRAGMA query_only=ON")
    return con

def inspect_source(con):
    integrity = con.execute("PRAGMA integrity_check").fetchone()[0]
    if integrity != "ok":
        raise RuntimeError(f"SQLite integrity check failed: {integrity}")

    names = [
        r[0] for r in con.execute("""
            SELECT name FROM sqlite_master
            WHERE type='table' AND name NOT LIKE 'sqlite_%'
            ORDER BY name
        """)
    ]
    tables = {}
    for name in names:
        q = ident(name)
        columns = con.execute(f"PRAGMA table_info({q})").fetchall()
        indexes = con.execute(f"PRAGMA index_list({q})").fetchall()
        fks = con.execute(f"PRAGMA foreign_key_list({q})").fetchall()
        count = con.execute(f"SELECT COUNT(*) FROM {q}").fetchone()[0]
        tables[name] = {
            "columns": columns,
            "indexes": indexes,
            "foreign_keys": fks,
            "row_count": count,
        }

    violations = con.execute("PRAGMA foreign_key_check").fetchall()
    return tables, integrity, violations

def make_column_definitions(name, columns):
    parts = []
    pk_columns = sorted(
        (c for c in columns if c["pk"]),
        key=lambda c: c["pk"],
    )
    identity_col = None
    if (
        len(pk_columns) == 1
        and "INT" in (pk_columns[0]["type"] or "").upper()
    ):
        identity_col = pk_columns[0]["name"]

    for c in columns:
        col = ident(c["name"])
        identity = c["name"] == identity_col
        definition = f"{col} {pg_type(c['type'], identity)}"

        if c["notnull"] and not identity:
            definition += " NOT NULL"

        default = pg_default(c["dflt_value"])
        if default is not None and not identity:
            definition += f" DEFAULT {default}"

        parts.append(definition)

    if pk_columns:
        pk = ", ".join(ident(c["name"]) for c in pk_columns)
        parts.append(f"PRIMARY KEY ({pk})")

    return parts, identity_col

def index_definitions(con, table, indexes):
    definitions = []
    for idx in indexes:
        # SQLite index origins: pk = primary key, u = table UNIQUE,
        # c = explicitly created index.
        origin = idx["origin"]
        index_name = idx["name"]

        info = con.execute(
            f"PRAGMA index_info({ident(index_name)})"
        ).fetchall()
        cols = [r["name"] for r in info]
        if not cols or any(c is None for c in cols):
            raise RuntimeError(f"Unsupported expression index: {index_name}")

        if origin == "pk":
            continue

        if origin == "u":
            definitions.append({
                "kind": "unique_constraint",
                "name": index_name,
                "columns": cols,
            })
            continue

        row = con.execute(
            "SELECT sql FROM sqlite_master WHERE type='index' AND name=?",
            (index_name,),
        ).fetchone()
        sql = row[0] if row else None
        if not sql:
            continue

        where = None
        match = re.search(r"\bWHERE\b(.*)$", sql, re.I | re.S)
        if match:
            where = match.group(1).strip()
            # SQLite treats this double-quoted value as a string in this
            # existing index; PostgreSQL needs a single-quoted literal.
            where = re.sub(r'"Member"', "'Member'", where)

        definitions.append({
            "kind": "index",
            "name": index_name,
            "columns": cols,
            "unique": bool(idx["unique"]),
            "where": where,
        })

    return definitions

def json_safe(value):
    if isinstance(value, bytes):
        return {"bytes_hex": value.hex()}
    if isinstance(value, Decimal):
        return str(value)
    if isinstance(value, (list, tuple)):
        return [json_safe(x) for x in value]
    if isinstance(value, dict):
        return {str(k): json_safe(v) for k, v in value.items()}
    return value

def main():
    if not SOURCE.is_file() or not BACKUP.is_file():
        raise RuntimeError("Source database or required recovery backup is missing.")

    source = open_sqlite(SOURCE)
    backup = open_sqlite(BACKUP)
    pg = None

    try:
        source_tables, _, source_fk = inspect_source(source)
        backup_tables, _, backup_fk = inspect_source(backup)

        source_total = sum(t["row_count"] for t in source_tables.values())
        backup_total = sum(t["row_count"] for t in backup_tables.values())

        if len(source_tables) != EXPECTED_TABLES or source_total != EXPECTED_ROWS:
            raise RuntimeError(
                f"Source baseline changed: {len(source_tables)} tables, "
                f"{source_total} rows. Expected {EXPECTED_TABLES}/{EXPECTED_ROWS}."
            )

        if set(source_tables) != set(backup_tables):
            raise RuntimeError("Source and backup table names differ.")

        for name in source_tables:
            if source_tables[name]["row_count"] != backup_tables[name]["row_count"]:
                raise RuntimeError(f"Source/backup row count differs: {name}")

        if source_fk or backup_fk:
            raise RuntimeError("Foreign-key violations exist in source or backup.")

        total_objects = source.execute("""
            SELECT COUNT(*) FROM sqlite_master
            WHERE type IN ('trigger', 'view')
              AND name NOT LIKE 'sqlite_%'
        """).fetchone()[0]
        if total_objects:
            raise RuntimeError(
                "Source contains triggers or views; migration stopped for manual conversion."
            )

        print("===== MIGRATION SUMMARY =====")
        print("Source:", SOURCE.relative_to(ROOT))
        print("Recovery backup:", BACKUP.relative_to(ROOT))
        print("Tables:", len(source_tables))
        print("Rows:", source_total)
        print("Source/backup row counts: match")
        print("Foreign-key violations: 0")
        print("Destination:", SCHEMA)
        print("Live application will remain on SQLite.")
        print()
        print("This will create a new isolated schema and import records.")
        print("It will not drop or replace an existing schema.")
        approval = input(f"Type IMPORT {SCHEMA} to continue: ").strip()
        if approval != f"IMPORT {SCHEMA}":
            print("Cancelled. No Supabase changes made.")
            return

        password = getpass.getpass("Supabase database password (hidden): ")
        os.environ.update({
            "SUPABASE_DB_HOST": "aws-1-eu-central-1.pooler.supabase.com",
            "SUPABASE_DB_PORT": "5432",
            "SUPABASE_DB_NAME": "postgres",
            "SUPABASE_DB_USER": "postgres.cmhleervgxnmceyiepba",
            "SUPABASE_DB_PASSWORD": password,
            "SUPABASE_DB_SCHEMA": SCHEMA,
        })

        from postgres_adapter import connect_postgres

        pg = connect_postgres()
        cur = pg.cursor()

        cur.execute(
            "SELECT EXISTS (SELECT 1 FROM information_schema.schemata WHERE schema_name=%s)",
            (SCHEMA,),
        )
        if cur.fetchone()[0]:
            raise RuntimeError(
                f"Destination schema {SCHEMA} already exists. "
                "Nothing was changed; inspect it before proceeding."
            )

        cur.execute(f"CREATE SCHEMA {ident(SCHEMA)}")

        # Create all tables first, with primary keys and safe identity columns.
        identities = {}
        indexes_by_table = {}
        foreign_keys_by_table = {}

        for table, details in source_tables.items():
            columns = details["columns"]
            parts, identity_col = make_column_definitions(table, columns)
            identities[table] = identity_col
            cur.execute(
                f"CREATE TABLE {ident(SCHEMA)}.{ident(table)} "
                f"({', '.join(parts)})"
            )
            indexes_by_table[table] = index_definitions(
                source, table, details["indexes"]
            )
            foreign_keys_by_table[table] = details["foreign_keys"]

        # Copy all rows, preserving explicit primary keys.
        for table, details in source_tables.items():
            columns = [c["name"] for c in details["columns"]]
            quoted_columns = ", ".join(ident(c) for c in columns)
            placeholders = ", ".join(["%s"] * len(columns))
            insert_sql = (
                f"INSERT INTO {ident(SCHEMA)}.{ident(table)} "
                f"({quoted_columns}) VALUES ({placeholders})"
            )

            qtable = ident(table)
            read_cursor = source.execute(f"SELECT * FROM {qtable}")
            batch = []
            imported = 0
            for row in read_cursor:
                batch.append(tuple(row[c] for c in columns))
                if len(batch) >= 200:
                    cur.executemany(insert_sql, batch)
                    imported += len(batch)
                    batch = []
            if batch:
                cur.executemany(insert_sql, batch)
                imported += len(batch)

            if imported != details["row_count"]:
                raise RuntimeError(
                    f"Import count mismatch for {table}: "
                    f"{imported} != {details['row_count']}"
                )

        # Recreate UNIQUE constraints and explicit indexes.
        for table, definitions in indexes_by_table.items():
            for item in definitions:
                if item["kind"] == "unique_constraint":
                    cols = ", ".join(ident(c) for c in item["columns"])
                    cname = ident(("uq_" + table + "_" + "_".join(item["columns"]))[:60])
                    cur.execute(
                        f"ALTER TABLE {ident(SCHEMA)}.{ident(table)} "
                        f"ADD CONSTRAINT {cname} UNIQUE ({cols})"
                    )
                else:
                    cols = ", ".join(ident(c) for c in item["columns"])
                    unique = "UNIQUE " if item["unique"] else ""
                    statement = (
                        f"CREATE {unique}INDEX {ident(item['name'])} "
                        f"ON {ident(SCHEMA)}.{ident(table)} ({cols})"
                    )
                    if item["where"]:
                        statement += " WHERE " + item["where"]
                    cur.execute(statement)

        # Add foreign keys only after all referenced rows exist.
        for table, fks in foreign_keys_by_table.items():
            for i, fk in enumerate(fks, start=1):
                cname = ident(f"fk_{table}_{i}")
                source_col = ident(fk["from"])
                ref_table = ident(fk["table"])
                ref_col = ident(fk["to"])
                statement = (
                    f"ALTER TABLE {ident(SCHEMA)}.{ident(table)} "
                    f"ADD CONSTRAINT {cname} FOREIGN KEY ({source_col}) "
                    f"REFERENCES {ident(SCHEMA)}.{ref_table} ({ref_col})"
                )
                on_delete = (fk["on_delete"] or "NO ACTION").upper()
                on_update = (fk["on_update"] or "NO ACTION").upper()
                allowed_actions = {
                    "NO ACTION", "RESTRICT", "CASCADE", "SET NULL", "SET DEFAULT"
                }
                if on_delete not in allowed_actions or on_update not in allowed_actions:
                    raise RuntimeError(f"Unsupported foreign-key action in {table}")
                statement += f" ON DELETE {on_delete} ON UPDATE {on_update}"
                cur.execute(statement)

        # Reset identity sequences to the imported maximum IDs.
        for table, identity_col in identities.items():
            if not identity_col:
                continue
            qtable = ident(table)
            qcol = ident(identity_col)
            cur.execute(
                f"SELECT COALESCE(MAX({qcol}), 0) FROM {ident(SCHEMA)}.{qtable}"
            )
            maximum = cur.fetchone()[0]
            cur.execute(
                "SELECT setval(pg_get_serial_sequence(%s, %s), %s, %s)",
                (f"{SCHEMA}.{table}", identity_col, max(maximum, 1), maximum > 0),
            )

        # Verify table row counts before committing.
        verification = {}
        for table, details in source_tables.items():
            cur.execute(
                f"SELECT COUNT(*) FROM {ident(SCHEMA)}.{ident(table)}"
            )
            actual = cur.fetchone()[0]
            expected = details["row_count"]
            verification[table] = {
                "source_rows": expected,
                "destination_rows": actual,
                "match": actual == expected,
            }
            if actual != expected:
                raise RuntimeError(
                    f"Verification failed for {table}: {actual} != {expected}"
                )

        pg.commit()

        result = {
            "completed_at_utc": datetime.now(timezone.utc).isoformat(),
            "status": "COMMITTED_AND_ROW_COUNTS_VERIFIED",
            "source": str(SOURCE.relative_to(ROOT)),
            "backup": str(BACKUP.relative_to(ROOT)),
            "destination_schema": SCHEMA,
            "source_table_count": len(source_tables),
            "source_total_rows": source_total,
            "destination_total_rows": sum(
                x["destination_rows"] for x in verification.values()
            ),
            "table_verification": verification,
            "production_cutover_performed": False,
            "live_application_changed": False,
        }
        REPORT.parent.mkdir(parents=True, exist_ok=True)
        REPORT.write_text(json.dumps(result, indent=2), encoding="utf-8")

        print("\n===== MIGRATION SUCCEEDED =====")
        print("Tables imported:", len(source_tables))
        print("Rows imported:", result["destination_total_rows"])
        print("All table row counts verified.")
        print("Report:", REPORT.relative_to(ROOT))
        print("Live application remains on SQLite.")
        print("Production cutover: NOT performed.")

    except Exception:
        if pg is not None:
            try:
                pg.rollback()
            except Exception:
                pass
        raise
    finally:
        source.close()
        backup.close()
        if pg is not None:
            try:
                pg.close()
            except Exception:
                pass
        os.environ.pop("SUPABASE_DB_PASSWORD", None)

if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print("\nMIGRATION STOPPED:", str(exc))
        print("The transaction was rolled back where possible.")
        print("Do not switch the live app to PostgreSQL.")
        sys.exit(1)
