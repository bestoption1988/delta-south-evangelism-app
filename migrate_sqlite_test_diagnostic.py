import getpass
import sqlite3
import sys
import pg8000.dbapi

SQLITE_BACKUP = (
    "data/backups/"
    "evangelism_before_postgres_20261014_070817.db"
)

PG_HOST = "aws-1-eu-central-1.pooler.supabase.com"
PG_PORT = 5432
PG_DATABASE = "postgres"
PG_USER = "postgres.cmhleervgxnmceyiepba"

TARGET_SCHEMA = "mcn_migration_test"


def quote(identifier):
    return '"' + identifier.replace('"', '""') + '"'


def pg_type(sqlite_type):
    t = (sqlite_type or "").upper()

    if "INT" in t:
        return "BIGINT"
    if any(x in t for x in ("CHAR", "CLOB", "TEXT")):
        return "TEXT"
    if any(x in t for x in ("REAL", "FLOA", "DOUB")):
        return "DOUBLE PRECISION"
    if "BLOB" in t or not t:
        return "BYTEA"
    if any(x in t for x in ("NUMERIC", "DECIMAL")):
        return "NUMERIC"
    if "BOOL" in t:
        return "BOOLEAN"
    return "TEXT"


def main():
    try:
        src = sqlite3.connect(SQLITE_BACKUP)
    except sqlite3.Error as exc:
        sys.exit(f"Cannot open SQLite backup: {exc}")

    src.row_factory = sqlite3.Row

    integrity = src.execute(
        "PRAGMA integrity_check"
    ).fetchone()[0]

    if integrity != "ok":
        src.close()
        sys.exit(f"SQLite integrity check failed: {integrity}")

    tables = [
        r[0] for r in src.execute("""
            SELECT name
            FROM sqlite_master
            WHERE type='table'
              AND name NOT LIKE 'sqlite_%'
            ORDER BY name
        """).fetchall()
    ]

    print("Source integrity:", integrity)
    print("Source tables:", len(tables))
    print("Target schema:", TARGET_SCHEMA)
    print()
    print("IMPORTANT: This creates a new isolated schema.")
    print("It will refuse to overwrite an existing target schema.")

    password = getpass.getpass(
        "Supabase database password (hidden): "
    )

    conn = None

    try:
        conn = pg8000.dbapi.connect(
            host=PG_HOST,
            port=PG_PORT,
            database=PG_DATABASE,
            user=PG_USER,
            password=password,
            timeout=25,
            ssl_context=True,
        )
        cur = conn.cursor()

        cur.execute("""
            SELECT schema_name
            FROM information_schema.schemata
            WHERE schema_name = %s
        """, (TARGET_SCHEMA,))

        if cur.fetchone():
            sys.exit(
                f"STOP: Schema {TARGET_SCHEMA!r} already exists. "
                "Nothing was changed. Inspect it before proceeding."
            )

        cur.execute(
            f"CREATE SCHEMA {quote(TARGET_SCHEMA)}"
        )

        # Create tables and preserve primary-key definitions.
        for table in tables:
            columns = src.execute(
                f"PRAGMA table_info({quote(table)})"
            ).fetchall()

            if not columns:
                raise RuntimeError(
                    f"No column information for {table}"
                )

            definitions = []

            integer_pk = (
                len([c for c in columns if c["pk"]]) == 1
                and next(
                    c for c in columns if c["pk"]
                )["type"].upper() == "INTEGER"
            )

            pk_columns = []

            for col in columns:
                name = col["name"]
                definition = (
                    f"{quote(name)} {pg_type(col['type'])}"
                )

                if integer_pk and col["pk"]:
                    definition += (
                        " GENERATED BY DEFAULT AS IDENTITY"
                        " PRIMARY KEY"
                    )
                else:
                    if col["notnull"]:
                        definition += " NOT NULL"

                    if col["dflt_value"] is not None:
                        default = str(col["dflt_value"]).strip()

                        # SQLite-specific defaults are deliberately
                        # not guessed or rewritten automatically.
                        if "AUTOINCREMENT" in default.upper():
                            raise RuntimeError(
                                f"Unsupported default in "
                                f"{table}.{name}: {default}"
                            )

                        definition += f" DEFAULT {default}"

                    if col["pk"]:
                        pk_columns.append(
                            (col["pk"], name)
                        )

                definitions.append(definition)

            if pk_columns and not integer_pk:
                pk_names = [
                    quote(name)
                    for _, name in sorted(pk_columns)
                ]
                definitions.append(
                    "PRIMARY KEY (" + ", ".join(pk_names) + ")"
                )

            ddl = (
                f"CREATE TABLE "
                f"{quote(TARGET_SCHEMA)}.{quote(table)} ("
                + ", ".join(definitions)
                + ")"
            )

            cur.execute(ddl)
            print("Created:", table)

        conn.commit()
        print("\nAll source table definitions created.")

        # Import records with explicit IDs preserved.
        total_rows = 0

        for table in tables:
            rows = src.execute(
                f"SELECT * FROM {quote(table)}"
            ).fetchall()

            columns = [
                item["name"]
                for item in src.execute(
                    f"PRAGMA table_info({quote(table)})"
                ).fetchall()
            ]

            if rows:
                names = ", ".join(quote(c) for c in columns)
                placeholders = ", ".join(
                    ["%s"] * len(columns)
                )

                insert_sql = (
                    f"INSERT INTO "
                    f"{quote(TARGET_SCHEMA)}.{quote(table)} "
                    f"({names}) VALUES ({placeholders})"
                )

                cur.executemany(
                    insert_sql,
                    [
                        tuple(row[c] for c in columns)
                        for row in rows
                    ],
                )

            total_rows += len(rows)
            print(f"Imported {table}: {len(rows)} rows")

        conn.commit()

        # Add declared foreign keys only after all rows are imported.
        fk_count = 0

        for table in tables:
            foreign_keys = src.execute(
                f"PRAGMA foreign_key_list({quote(table)})"
            ).fetchall()

            for fk in foreign_keys:
                name = (
                    f"fk_{table}_{fk['id']}_{fk['seq']}"
                )[:60]

                cur.execute(
                    f"ALTER TABLE "
                    f"{quote(TARGET_SCHEMA)}.{quote(table)} "
                    f"ADD CONSTRAINT {quote(name)} "
                    f"FOREIGN KEY ({quote(fk['from'])}) "
                    f"REFERENCES "
                    f"{quote(TARGET_SCHEMA)}."
                    f"{quote(fk['table'])} "
                    f"({quote(fk['to'])})"
                )
                fk_count += 1

        conn.commit()

        # Align generated identity sequences with imported IDs.
        for table in tables:
            columns = src.execute(
                f"PRAGMA table_info({quote(table)})"
            ).fetchall()

            integer_pk = [
                c for c in columns
                if c["pk"] and c["type"].upper() == "INTEGER"
            ]

            if len(integer_pk) == 1:
                col = integer_pk[0]["name"]
                relation = (
                    TARGET_SCHEMA + "." + table
                )

                cur.execute(
                    f"SELECT MAX({quote(col)}) "
                    f"FROM {quote(TARGET_SCHEMA)}."
                    f"{quote(table)}"
                )
                maximum = cur.fetchone()[0]

                cur.execute(
                    "SELECT pg_get_serial_sequence(%s, %s)",
                    (relation, col),
                )
                sequence = cur.fetchone()[0]

                if sequence and maximum is not None:
                    cur.execute(
                        "SELECT setval(%s, %s, true)",
                        (sequence, maximum),
                    )

        conn.commit()

        # Compare every source table's count with PostgreSQL.
        print("\nROW COUNT VERIFICATION")
        failures = []

        for table in tables:
            source_count = src.execute(
                f"SELECT COUNT(*) FROM {quote(table)}"
            ).fetchone()[0]

            cur.execute(
                f"SELECT COUNT(*) FROM "
                f"{quote(TARGET_SCHEMA)}.{quote(table)}"
            )
            target_count = cur.fetchone()[0]

            status = "OK" if source_count == target_count else "MISMATCH"
            print(
                f"{status}: {table}: "
                f"SQLite={source_count}, PostgreSQL={target_count}"
            )

            if source_count != target_count:
                failures.append(table)

        print("\nSOURCE TABLES:", len(tables))
        print("SOURCE ROWS:", total_rows)
        print("DECLARED FOREIGN KEYS:", fk_count)

        if failures:
            print("VERIFICATION FAILED:", ", ".join(failures))
        else:
            print("ROW COUNTS VERIFIED SUCCESSFULLY.")

        print(
            "\nNOTE: This is a migration test, not a production cutover."
        )
        print(
            "Indexes, triggers, application compatibility, and "
            "all data types still require separate validation."
        )

        cur.close()

    except Exception as exc:
        if conn:
            try:
                conn.rollback()
            except Exception:
                pass

        print("\nMIGRATION TEST STOPPED.")
        print("Error:", type(exc).__name__, str(exc))
        print(
            "The existing public schema and SQLite backup "
            "were not intentionally modified."
        )
        sys.exit(1)

    finally:
        src.close()
        if conn:
            conn.close()


if __name__ == "__main__":
    main()
